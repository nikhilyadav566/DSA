#include<iostream>
using namespace std;

int main() {                          // Main function: Program starts here.
    cout << "Enter your number" << endl;   // Displays a message asking for input.
    int a;                            // Declares an integer variable to store the input.
    cin >> a;                         // Takes input from the user and stores it in 'a'.
    cout << "You entered " << a << endl;   // Displays the entered number.
    return 0;                         // Ends the program successfully.
}