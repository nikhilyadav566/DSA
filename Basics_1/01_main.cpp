#include<iostream>          // Includes the input/output library.

int main()                  // Main function: program starts here.
{
    std::cout << "Happy Journey";   // Prints "Happy Journey" on the screen.
}                           // End of the main function.



//  Notes
//1.  #include<iostream> :-> Includes the iostream library, which allows us to use input (cin) and output (cout).
//2.  main():-> It is the starting point of every C++ program. Program execution begins here.
//3.  int:->   int means the function returns an integer value.
//4.  std:->   std stands for Standard. It is the standard namespace in C++ that contains built-in features like cout, cin, endl, string, etc.
//5.  :: :->   It is called the scope resolution operator. It tells the compiler to use something from the std namespace.

