#include<iostream>
using namespace std;  // Allows us to use cout, cin, endl, etc., without writing std::

int main() {
    cout << "Hello India" << endl;  // Prints text and moves to the next line.
    cout << '\n';                   // Prints another new line.
    cout << "Hii";                  // Prints "Hii".
}

