//  There are two types of array

// 1. Static Array    (Size is fixed when the array is created)

//   These are static array in which an array whose size is fixed when it is created and cannot be changed later.
//      int arr[5] = {10,20,30,40,50};
//           5 -> fixed size

//    int arr[] = {1,2,3};
//    automatically determined  -> 3
//    It is static array because its size is fixed after creation.

// 2. Dynamic Array    (Size is decided/allocated at runtime)

//   A dynamic array is an array whose memory is allocated at runtime ,
//    so its size can be decided while the program is running.
