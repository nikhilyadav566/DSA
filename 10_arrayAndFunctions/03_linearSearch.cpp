//  Linear Search in Array

// Linear Search is a simple method of finding a particular element (called a key) in an array
//      by checking each element one by one from the beginning to the end.

// For example:

// Array:  2   5   8   10   15
//         ↓
// Search for 10

// We check:

// 2  →  10? ❌
// 5  →  10? ❌
// 8  →  10? ❌
// 10 →  10? ✅ Found

// So, Linear Search = checking array elements one by one until the element is found or the array ends.
