// Unlike a normal 2D array, every row in a 2D vector does NOT need to have
// the same number of columns.


// Example:

//     vector<vector<int>> arr = {
//         {1, 2, 3},
//         {4, 5},
//         {6, 7, 8, 9}
//     };


// Visualization:

//     Row 0 → 1 2 3
//     Row 1 → 4 5
//     Row 2 → 6 7 8 9


// This is called a:

//     Jagged Array / Irregular 2D Vector


// IMPORTANT DIFFERENCE:

// Normal 2D array usually has fixed columns:

//     int arr[3][3];


// 2D vector can have different sizes for each row.