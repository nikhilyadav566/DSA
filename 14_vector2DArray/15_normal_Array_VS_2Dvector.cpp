//                     PART 16: NORMAL ARRAY VS 2D VECTOR
// ===============================================================================


// NORMAL 2D ARRAY:

//     int arr[3][4];


// Characteristics:

//     1. Fixed size.
//     2. Rows and columns usually known beforehand.
//     3. Memory structure is contiguous.
//     4. Less flexible.



// 2D VECTOR:

//     vector<vector<int>> arr(3, vector<int>(4));


// Characteristics:

//     1. Dynamic size.
//     2. Rows can grow.
//     3. Individual rows can have different sizes.
//     4. More flexible.
//     5. Easier when dimensions are decided at runtime.
