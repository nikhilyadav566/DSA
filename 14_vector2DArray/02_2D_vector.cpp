// ===============================================================================
//                             PART 2: WHAT IS 2D VECTOR?
// ===============================================================================

// A 2D vector is a vector containing other vectors.

// Syntax:

//     vector<vector<int>> arr;


// UNDERSTANDING THE SYNTAX:
// -------------------------
// First:
//     vector<int>
// means:
//     A vector containing integers.

// Example:
//     vector<int> row = {1, 2, 3};


// Now:
//     vector<vector<int>>
// means:
//     A vector containing vectors of integers.


// IMPORTANT IDEA:

//     vector<int>
//         ↓
//     Stores integers


//     vector<vector<int>>
//         ↓
//     Stores vector<int>


// So, a 2D vector can represent rows and columns.
